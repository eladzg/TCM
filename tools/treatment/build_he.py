"""Build the Hebrew dictionary for the Chinese text the interview prototype shows.

Reads the reviewed translation lists in kb/translations/he/*.txt (one `chinese|hebrew` pair per line)
and writes app/interview/he_dict.js (window.TCM_HE = {chinese: hebrew}) with only the strings the
page can show: pattern names and GB/T 16751.2 text from kb.js, and point, herb, formula, method,
dose, quote and safety-note strings from treatment_kb.js.

The translations are DRAFTS written with Claude and wait for clinician review; the page always
shows the Chinese original and a link to the source next to them.

Usage:
    python3 tools/treatment/build_he.py           # write he_dict.js, list missing strings
    python3 tools/treatment/build_he.py --check   # exit 1 if a shown string has no translation
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APP = ROOT / "app" / "interview"
TR = ROOT / "kb" / "translations" / "he"
OUT = APP / "he_dict.js"
HAN = re.compile(r"[一-鿿]")
# 十八反 / 十九畏 notes are rendered by a template from the herb names (app/interview/i18n.js).
TEMPLATE_NOTE = re.compile(r"^(十八反|十九畏): (\S+) (反|畏) (\S+)")


def load_js(path):
    s = path.read_text(encoding="utf-8")
    return json.loads(s[s.index("=") + 1:].rstrip().rstrip(";"))


def shown_strings():
    """{category: set(chinese strings)} the page can show."""
    kb, tx = load_js(APP / "kb.js"), load_js(APP / "treatment_kb.js")
    cats = {}

    def add(cat, s):
        if s and HAN.search(s):
            cats.setdefault(cat, set()).add(s)

    for s in kb["syndromes"]:
        add("pattern_name", s["zh"])
        add("gb_text", s.get("gbtext") or "")
        for link in s["links"]:
            add("gb_ev", link.get("ev_zh", ""))
            if link["src"] == ["GB"]:
                add("gb_ev", link["ev"])
    for p in tx["points"].values():
        add("point_name", p["zh"])
        for f in p["find"]:
            if f["src"] == "WS-ZJDC":
                add("zjdc_ev", f["ev"])
    for h in tx["herbs"].values():
        add("herb_name", h["zh"])
    for link in tx["links"].values():
        for h in link["h"]:
            for i in h["a"]:
                add("herb_act", tx["herbs"][h["id"]]["act"][i])
        for f in link["fm"]:
            if f.get("q"):
                add("clause_ev", f["q"]["ev"])
    for f in tx["formulas"].values():
        add("formula_name", f["zh"])
        for c in f["comp"]:
            add("dose", c["d"])
        for x in f["find"]:
            add("clause_ev", x["ev"])
    for m in tx["methods"]:
        add("method", m["zh"])
    for r in tx["safety"]:
        if not TEMPLATE_NOTE.match(r["note"]):
            add("safety_note", r["note"])
    return cats


def load_translations():
    out = {}
    for path in sorted(TR.glob("*.txt")):
        for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if not line.strip():
                continue
            zh, sep, he = line.partition("|")
            if not sep or not he.strip():
                raise SystemExit(f"{path.name}:{n}: expected 'chinese|hebrew'")
            out.setdefault(zh, he.strip())
    return out


def build():
    cats = shown_strings()
    tr = load_translations()
    used = sorted(set().union(*cats.values()))
    missing = {c: sorted(s for s in v if s not in tr) for c, v in cats.items()}
    return {s: tr[s] for s in used if s in tr}, {c: v for c, v in missing.items() if v}


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    data, missing = build()
    for cat, items in sorted(missing.items()):
        print(f"missing {cat}: {len(items)} (e.g. {items[0]})")
    if "--check" in argv:
        return 1 if missing else 0
    OUT.write_text("// Generated by tools/treatment/build_he.py from kb/translations/he. Do not edit by hand.\n"
                   "// Draft Hebrew translations, awaiting clinician review.\n"
                   "window.TCM_HE = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    print(f"{len(data)} translations -> {OUT} ({OUT.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
