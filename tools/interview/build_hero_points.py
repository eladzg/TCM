"""The opening screen's figure as a cloud of dots: app/interview/hero_points.js.

Samples the skin of app/interview/body.glb ("Male base muscular anatomy" by Harshit Prajapati,
Sketchfab, CC BY 4.0) evenly by area, thins the samples on a grid so the dots are spaced alike, and
writes their positions and normals, quantised, as base64. The opening screen draws these dots with
one small shader instead of loading the 4 MB model, so it opens fast and moves freely.

    python3 tools/interview/build_hero_points.py [--count 30000]
"""
import argparse
import base64
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "treatment"))
from build_points3d import GLB, load_mesh  # noqa: E402

OUT = ROOT / "app" / "interview" / "hero_points.js"


def sample(count, seed=7):
    V, N, F = load_mesh(GLB)
    A, B, C = V[F[:, 0]], V[F[:, 1]], V[F[:, 2]]
    area = 0.5 * np.linalg.norm(np.cross(B - A, C - A), axis=1)
    rng = np.random.default_rng(seed)
    m = count * 5
    tri = rng.choice(len(F), size=m, p=area / area.sum())
    r1, r2 = rng.random(m), rng.random(m)
    s = np.sqrt(r1)
    u, v, w = 1 - s, s * (1 - r2), s * r2
    P = u[:, None] * A[tri] + v[:, None] * B[tri] + w[:, None] * C[tri]
    f = F[tri]
    Nn = u[:, None] * N[f[:, 0]] + v[:, None] * N[f[:, 1]] + w[:, None] * N[f[:, 2]]
    Nn /= np.linalg.norm(Nn, axis=1)[:, None] + 1e-12
    # Thin on a grid: one dot per cell, the cell sized so about `count` dots remain.
    lo = P.min(axis=0)
    cell = np.sqrt(area.sum() / count) * 0.92
    for _ in range(12):
        key = np.floor((P - lo) / cell).astype(np.int64)
        _, keep = np.unique(key[:, 0] * 1_000_003 ** 2 + key[:, 1] * 1_000_003 + key[:, 2], return_index=True)
        if abs(len(keep) - count) < count * 0.03:
            break
        cell *= (len(keep) / count) ** 0.5
    keep = np.sort(keep)
    return P[keep], Nn[keep]


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--count", type=int, default=30000)
    a = ap.parse_args()
    P, Nn = sample(a.count)
    lo, hi = P.min(axis=0), P.max(axis=0)
    q = np.round((P - lo) / (hi - lo) * 65535).astype("<u2")
    n = np.clip(np.round(Nn * 127), -127, 127).astype("i1")
    b64 = lambda arr: base64.b64encode(arr.tobytes()).decode("ascii")
    OUT.write_text(
        "// Generated by tools/interview/build_hero_points.py: dots on the skin of body.glb (\"Male base muscular\n"
        "// anatomy\" by Harshit Prajapati, Sketchfab, CC BY 4.0) for the opening screen. Do not edit.\n"
        "window.TCM_HERO_POINTS = {n: %d, lo: [%s], hi: [%s],\n  p: \"%s\",\n  nrm: \"%s\"};\n"
        % (len(P), ", ".join("%.6f" % x for x in lo), ", ".join("%.6f" % x for x in hi), b64(q), b64(n)),
        encoding="utf-8")
    print(f"{len(P)} dots -> {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
