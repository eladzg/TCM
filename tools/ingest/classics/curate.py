"""Turn the staging records of the classics and WHO 2022 into draft rows in kb/curation/*.yaml.

Writes points.yaml (AcuAtlas + Zhenjiu Dacheng), herbs.yaml (Bencao Beiyao + every herb the
formulas name), formulas.yaml (Shanghan Lun + Jingui Yaolue) and safety_rules.yaml (pregnancy,
toxicity, 十八反 pairs, classical needling/moxibustion bans), and, from the WHO 2022 terminology,
syndromes.yaml (425 patterns), and manifestations.yaml (symptoms, signs, tongue and
pulse findings). WHO lists formula categories only, so formulas keep their classical names. Every generated row is `draft`.
A row already in the file with status `reviewed` or `approved` is kept exactly as it is, so the
clinician's work survives a rerun. Gram doses and syndrome weights are never generated.

Usage:
    python3 tools/ingest/classics/curate.py
"""

import json
import re
import sys

import yaml

from common import ROOT, STAGING, herb_key, latest_raw, read_jsonl, to_id, to_pinyin_title

CURATION = ROOT / "kb" / "curation"

# Formula ingredient names -> the Bencao Beiyao heading for the same drug (same drug, other name).
HERB_ALIASES = {
    "肥梔子": "梔子", "麻仁": "大麻仁", "麻子仁": "大麻仁", "代赭": "代赭石", "太一禹餘糧": "禹余糧",
    "黃檗": "黃柏", "黃蘗": "黃柏", "厚樸": "厚朴", "栝蔞根": "天花粉", "香豉": "淡豆豉", "葶藶子": "葶藶",
    "茵陳蒿": "茵陳", "萎蕤": "葳蕤", "蔥白": "蔥", "瓜蒂": "甜瓜蒂", "蜀椒": "川椒", "乾姜": "乾薑",
    "芒消": "芒硝", "芎藭": "川芎", "芎窮": "川芎", "薯蕷": "山藥", "白斂": "白蘞", "牡丹": "牡丹皮",
    "生葛": "葛根", "大附子": "附子", "牡蠣熬": "牡蠣", "牡丹去心": "牡丹皮", "桃仁去皮": "桃仁",
    "蜜": "蜂蜜", "訶梨勒": "訶子", "竹葉": "淡竹葉", "商陸根": "商陸", "葵子": "冬葵子", "鱉甲手指大": "鱉甲", "生地黃汁": "生地黃", "石葦": "石韋", "膠飴": "飴糖", "人尿": "童便",
    # Han-dynasty texts write plain 芍藥; Bencao Beiyao's entry is 白芍藥 (赤芍藥 is a note under it).
    "芍藥": "白芍藥",
}
# Tokens the ingredient parser left behind that are not drugs (preparation words, stray notes).
NOT_DRUGS = {"条", "為膏", "深師有生薑", "粉", "重", "尖", "汁", "）", "鹽"}
NEEDLE_BAN_RE = re.compile(r"禁針|不可針|不宜針")
MOXA_BAN_RE = re.compile(r"禁灸|不可灸|不宜灸")
PREG_POINT_RE = re.compile(r"[^，。]*(?:孕|妊娠|墮胎|胎)[^。]*。?")


def dump(name, rows):
    path = CURATION / f"{name}.yaml"
    kept = {}
    if path.exists():
        for row in yaml.safe_load(path.read_text("utf-8")) or []:
            if row.get("status") in ("reviewed", "approved"):
                kept[next(iter(row.values()))] = row
    merged = [kept.get(next(iter(r.values())), r) for r in rows]
    header = (f"# Generated by tools/ingest/classics/curate.py from kb/staging. Rows stay draft until the clinician\n"
              f"# reviews them; reviewed/approved rows are never overwritten by a rerun.\n")
    body = yaml.safe_dump(merged, allow_unicode=True, sort_keys=False, width=10_000)
    path.write_text(header + body, encoding="utf-8")
    return len(merged), len(kept)


def ref(source_id, field, locator, quote=None):
    r = {"source_id": source_id, "field": field, "locator": locator}
    if quote:
        r["quote"] = quote
    return r


# ---------- points ----------

def build_points():
    path, _ = latest_raw("ACUATLAS")
    atlas = json.loads(path.read_text("utf-8"))["points"]
    classical = {r["point_id"]: r for r in read_jsonl(STAGING / "WS-ZJDC" / "points.jsonl")}
    rows = []
    for p in atlas:
        pid = p["id"].replace("-", "").replace("LV", "LR")
        loc = f"acupoints.json {p['id']}"
        indications = "; ".join(x for x in (p["indications"], p["secondaryIndications"]) if x)
        needling = "; ".join(f"{k}: {v}" for k, v in (("depth", p["depth"]), ("moxibustion", p["moxibustion"])) if v)
        row = {"point_id": pid, "channel_id": f"CH.{pid[:2]}", "name_pinyin": p["name"],
               "name_zh": p["hanzi"], "name_en": p["english"], "location": p["location"],
               "actions": p["actions"], "indications": indications, "needling_notes": needling,
               "cautions": p["cautionNote"] if p["isCaution"] else None}
        sources = [ref("ACUATLAS", f, loc) for f in ("location", "actions", "indications", "needling_notes", "cautions")
                   if row[f]]
        if pid in classical:
            c = classical[pid]
            row["classical"] = c["text"]
            sources.append(ref("WS-ZJDC", "classical", f"{c['volume']} 考正穴法, line {c['line']}"))
        row = {k: v for k, v in row.items() if v not in (None, "")}
        row.update(status="draft", sources=sources)
        rows.append(row)
    return rows, classical


# ---------- herbs and formulas ----------

class HerbIndex:
    """Herb rows keyed by folded Chinese name, with collision-free ids."""

    def __init__(self):
        self.rows, self.by_key, self.ids = [], {}, set()

    def get(self, name_zh):
        name_zh = HERB_ALIASES.get(name_zh, name_zh)
        return self.by_key.get(herb_key(name_zh))

    def alias(self, name_zh, row):
        self.by_key.setdefault(herb_key(name_zh), row)

    def add(self, name_zh):
        name_zh = HERB_ALIASES.get(name_zh, name_zh)
        if (row := self.get(name_zh)) is not None:
            return row
        hid, n = to_id("HERB", name_zh), 2
        while hid in self.ids:
            hid, n = f"{to_id('HERB', name_zh)}_{n}", n + 1
        row = {"herb_id": hid, "name_pinyin": to_pinyin_title(name_zh), "name_zh": name_zh}
        self.ids.add(hid)
        self.by_key[herb_key(name_zh)] = row
        self.rows.append(row)
        return row


def build_herbs(index):
    for r in read_jsonl(STAGING / "GUT-BENCAO-BEIYAO" / "herbs.jsonl"):
        row = index.add(r["name_zh"])
        for other in r["other_names"]:
            index.alias(other, row)
        loc = f"{r['section']}·{r['name_zh']} (Gutenberg #26888, line {r['line']})"
        sources = row.setdefault("sources", [])
        fields = {"nature": r["nature"], "flavour": r["flavour"], "channels_entered": r["channels"] or None,
                  "actions": r["summary"], "pregnancy_caution": " ".join(r["pregnancy"]) or None,
                  "classical": r["text"]}
        for f, v in fields.items():
            if v:
                row[f] = v
                sources.append(ref("GUT-BENCAO-BEIYAO", f, loc, r["summary"] if f in ("nature", "flavour") else None))
        row["_bencao"] = r


def clause_label(source, clause):
    return f"條{clause}" if source == "GUT-SHANGHAN" else f"篇{clause}"


def build_formulas(index):
    formulas, by_key = [], {}
    for source in ("GUT-SHANGHAN", "WS-JINGUI"):
        clauses = {c["clause"]: c for c in read_jsonl(STAGING / source / "clauses.jsonl")}
        for f in read_jsonl(STAGING / source / "formulas.jsonl"):
            if not f["herbal"]:
                continue
            key = herb_key(f["name_zh"])
            row = by_key.get(key)
            if row is None:
                row = {"formula_id": to_id("FORM", f["name_zh"]), "name_pinyin": to_pinyin_title(f["name_zh"]),
                       "name_zh": f["name_zh"], "status": "draft", "sources": []}
                by_key[key] = row
                formulas.append(row)
            label = "傷寒論" if source == "GUT-SHANGHAN" else "金匱要略"
            texts = [f"{label} {clause_label(source, n)}：{clauses[n]['text']}" for n in f["clauses"]]
            if texts:
                row["indications"] = "\n".join(filter(None, [row.get("indications"), *texts]))
                row["sources"].append(ref(source, "indications", ", ".join(clause_label(source, n) for n in f["clauses"])))
            if "composition" not in row:
                comp, seen = [], set()
                for item in f["ingredients"]:
                    name = item["name"]
                    if name in NOT_DRUGS or len(name) > 5 or not name:
                        continue
                    herb = index.add(name)
                    if herb["herb_id"] in seen:
                        continue
                    seen.add(herb["herb_id"])
                    entry = {"herb_id": herb["herb_id"]}
                    if item["dose_original"]:
                        entry["dose_original"] = item["dose_original"] + (f"（{item['prep']}）" if item["prep"] else "")
                    comp.append(entry)
                if comp:
                    row["composition"] = comp
                    where = f["chapter"] + (f", after {clause_label(source, f['after_clause'])}" if f["after_clause"] else "")
                    row["sources"].append(ref(source, "composition", where, f["ingredient_text"]))
                if f["preparation"]:
                    row["classical"] = f["preparation"]
                    row["sources"].append(ref(source, "classical", f"{f['chapter']}, {f['name_zh']}方"))
    return formulas


# ---------- safety rules ----------

def build_safety(index, classical_points):
    rules, pairs = [], set()
    for row in index.rows:
        r = row.get("_bencao")
        if not r:
            continue
        loc = f"{r['section']}·{r['name_zh']} (Gutenberg #26888, line {r['line']})"
        stem = row["herb_id"].removeprefix("HERB.")
        if r["pregnancy"]:
            text = " ".join(r["pregnancy"])
            severity = "contraindicated" if re.search(r"墮胎|落胎|下胎|忌|禁", text) else "caution"
            rules.append({"rule_id": f"SAFE.PREG.{stem}", "condition": "pregnancy", "entity_ids": [row["herb_id"]],
                          "severity": severity, "note": text, "status": "draft",
                          "sources": [ref("GUT-BENCAO-BEIYAO", "entity_ids", loc, text)]})
        if r["toxicity"]:
            rules.append({"rule_id": f"SAFE.TOXIC.{stem}", "condition": "other", "entity_ids": [row["herb_id"]],
                          "severity": "caution", "note": f"{r['toxicity']} (toxic per Bencao Beiyao)",
                          "status": "draft", "sources": [ref("GUT-BENCAO-BEIYAO", "entity_ids", loc, r["summary"])]})
        for other in r["relations"].get("fan", []):
            target = index.get(other)
            if target is None or target is row:
                continue
            pair = tuple(sorted((row["herb_id"], target["herb_id"])))
            if pair in pairs:
                continue
            pairs.add(pair)
            a, b = (p.removeprefix("HERB.") for p in pair)
            rules.append({"rule_id": f"SAFE.FAN.{a}.{b}", "condition": "other", "entity_ids": list(pair),
                          "severity": "contraindicated",
                          "note": f"十八反: {row['name_zh']} 反 {target['name_zh']} (do not combine)",
                          "status": "draft", "sources": [ref("GUT-BENCAO-BEIYAO", "entity_ids", loc, f"反{other}")]})
    for pid, c in sorted(classical_points.items()):
        loc = f"{c['volume']} 考正穴法, line {c['line']}"
        stem = pid
        if NEEDLE_BAN_RE.search(c["text"]):
            rules.append({"rule_id": f"SAFE.NO_NEEDLE.{stem}", "condition": "other", "entity_ids": [pid],
                          "severity": "caution", "note": "Zhenjiu Dacheng lists needling as forbidden (禁針) here; "
                          "modern practice may differ, check the point's cautions", "status": "draft",
                          "sources": [ref("WS-ZJDC", "entity_ids", loc, NEEDLE_BAN_RE.search(c["text"]).group(0))]})
        if MOXA_BAN_RE.search(c["text"]):
            rules.append({"rule_id": f"SAFE.NO_MOXA.{stem}", "condition": "other", "entity_ids": [pid],
                          "severity": "caution", "note": "Zhenjiu Dacheng lists moxibustion as forbidden (禁灸) here",
                          "status": "draft",
                          "sources": [ref("WS-ZJDC", "entity_ids", loc, MOXA_BAN_RE.search(c["text"]).group(0))]})
        if m := PREG_POINT_RE.search(c["text"]):
            rules.append({"rule_id": f"SAFE.PREG.{stem}", "condition": "pregnancy", "entity_ids": [pid],
                          "severity": "caution", "note": m.group(0), "status": "draft",
                          "sources": [ref("WS-ZJDC", "entity_ids", loc, m.group(0))]})
    return rules


# ---------- WHO 2022 patterns and manifestations ----------

# Pattern group heading (Chinese) -> the 2-3 letter middle part of the syndrome id.
PATTERN_GROUPS = {"八纲证类": "EP", "病因证类": "ETI", "阴阳气血津液精髓证类": "QB", "心系证类": "HT", "肺系证类": "LU",
                  "脾系证类": "SP", "肝系证类": "LR", "肾系证类": "KI", "脏腑兼证类": "ZF", "精室证类": "ESS",
                  "胞宫证类": "UT", "经络证类": "MER", "十二正经证类": "MER", "奇经八脉证类": "EXM", "三焦证类": "SJ",
                  "肌肤筋骨证类": "SKB", "六经证类": "SIX", "卫气营血证类": "WQY", "其他证类": "OTH"}
# Rows in the four-examinations section that name a method or concept rather than a finding.
NOT_FINDING_RE = re.compile(r"^(A (diagnostic )?method|A pulse-taking terminology|The (tongue|pulse|normal)|This refers to)")


def who_terms():
    path = STAGING / "WHO-ISTTCM-2022" / "terms.jsonl"
    return read_jsonl(path) if path.exists() else []


def who_ref(field, t, quote=None):
    return ref("WHO-ISTTCM-2022", field, f"WGM2 {t['number']} ({t['term_zh']}), p. {t['page']}", quote)


def build_syndromes(terms):
    rows, ids = [], set()
    for t in terms:
        if t["part"] != "patterns" or not t["term_zh"]:
            continue
        group = next((code for zh, code in PATTERN_GROUPS.items() if (t["category_zh"] or "").startswith(zh[:4])), "OTH")
        sid = to_id(f"SYN.{group}", t["term_zh"].removesuffix("证"))
        if sid in ids:
            continue
        ids.add(sid)
        presentation, aetiology = t["manifestations"], None
        if presentation and (m := re.search(r"\s*(This pattern (?:often )?occurs .*)$", presentation)):
            presentation, aetiology = presentation[:m.start()].strip() or None, m.group(1)
        row = {"syndrome_id": sid, "name_en": t["term_en"], "name_pinyin": t["pinyin"], "name_zh": t["term_zh"],
               "category": t["category_en"], "presentation": presentation, "aetiology": aetiology,
               "tongue": t["tongue"], "pulse": t["pulse"]}
        row = {k: v for k, v in row.items() if v}
        row["status"] = "draft"
        row["sources"] = [who_ref(f, t) for f in ("presentation", "aetiology", "tongue", "pulse") if f in row]
        rows.append(row)
    return rows


def manifestation_kind(t):
    n = t["number"]
    if 634 <= n < 700:
        return "tongue"
    if 849 <= n < 930:
        return "pulse" if "pulse" in t["term_en"].lower() else "sign"
    return "symptom" if 724 <= n < 849 else "sign"


def build_manifestations(terms):
    rows, ids = [], set()
    for t in terms:
        if t["part"] != "diagnosis" or not 557 <= t["number"] < 930 or not t["term_zh"]:
            continue
        if NOT_FINDING_RE.match(t["definition"] or ""):
            continue
        mid = to_id("MAN", t["term_zh"])
        if mid in ids:
            continue
        ids.add(mid)
        rows.append({"manifestation_id": mid, "term_en": t["term_en"], "term_zh": t["term_zh"],
                     "kind": manifestation_kind(t), "definition": t["definition"], "status": "draft",
                     "sources": [who_ref("definition", t)]})
    return rows


def main():
    points, classical_points = build_points()
    index = HerbIndex()
    build_herbs(index)
    formulas = build_formulas(index)
    safety = build_safety(index, classical_points)
    terms = who_terms()
    syndromes, manifestations = build_syndromes(terms), build_manifestations(terms)
    herbs = []
    for row in index.rows:
        row.pop("_bencao", None)
        sources = row.pop("sources", [])
        herbs.append({**row, "status": "draft", "sources": sources})
    tables = [("points", points), ("herbs", herbs), ("formulas", formulas), ("safety_rules", safety),
              ("syndromes", syndromes), ("manifestations", manifestations)]
    for name, rows in tables:
        if not rows:
            continue
        total, kept = dump(name, rows)
        print(f"kb/curation/{name}.yaml: {total} rows ({kept} reviewed/approved kept as they were)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
